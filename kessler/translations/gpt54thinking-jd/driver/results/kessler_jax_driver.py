#!/usr/bin/env python3
"""
Kessler Microphysics Driver Script

Replaces the original Fortran kessler module with JAX bridge implementation.
This driver:
1. Reads shared inputs from data/exp2_jd/fortran_io/inputs/  (generated by generate_fortran_inputs.py)
2. Calls kessler_init_bridge (replaces CALL kessler_init in Fortran)
3. Calls kessler_run_bridge  (replaces CALL kessler_run  in Fortran) — via
   bridge contract 1 (host-facing) or contract 2 (device-resident), see
   LAFT_DRIVER_MODE below
4. Saves results to out/driver/

Author: Auto-generated by LAFT for the kessler project
Platform: NCAR Derecho (NVIDIA A100)
"""

# --- JAX x64 MUST come before any JAX import ---
import os
os.environ["JAX_ENABLE_X64"] = "1"

import jax
jax.config.update("jax_enable_x64", True)

import sys
import json
import traceback
from datetime import datetime
import numpy as np
from pathlib import Path

# Add project root to path
project_root = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(project_root))

# Import BRIDGE code (replaces Fortran module)
from out.bridge.kessler_init_bridge import kessler_init_bridge
from out.bridge.kessler_run_bridge import (
    kessler_run_bridge, kessler_run_bridge_device, to_device)

# ---------------------------------------------------------------------------
# Driver mode — which bridge contract carries the array procedure
# ---------------------------------------------------------------------------
#   host            (default) contract 1: the host-facing bridge, NumPy in and
#                   out (H2D of the 11 array inputs + ONE batched device_get
#                   per call). The path every prior validation used.
#   device_resident contract 2: the arrays are uploaded once here, the
#                   *_bridge_device entry is called with them already on the
#                   GPU, and ONE batched jax.device_get fetches the outputs.
#                   Same jitted code (contract 1 wraps contract 2), so the
#                   outputs are bit-identical; the comparison stage gates this
#                   mode exactly like the host mode.
#
# Kessler has ONE array procedure, so this mode does not save a round trip the
# way it does on kessler_update's 3-procedure step chain (there: 857 ms → 4.8 ms
# at ncol=1e6). Here it is a correctness/parity path — it proves contract 2
# end-to-end against the Fortran ground truth — and it is what a GPU-resident
# host model would call to keep the state on the device across timesteps.
# kessler_init is scalar-only: it has no device entry and stays contract 1 in
# both modes.
#
# Select via the environment (PBS forwards it):
#   qsub -v LAFT_DRIVER_MODE=device_resident pbsJobs/jax_driver_gpu.sh
DRIVER_MODE = os.environ.get("LAFT_DRIVER_MODE", "host").strip().lower()
if DRIVER_MODE not in ("host", "device_resident"):
    raise SystemExit(f"LAFT_DRIVER_MODE must be 'host' or 'device_resident', "
                     f"got {DRIVER_MODE!r}")

# ---------------------------------------------------------------------------
# Input directory — shared with Fortran driver
# ---------------------------------------------------------------------------
INP_DIR = project_root / "data" / "exp2_jd" / "fortran_io" / "inputs"

# ---------------------------------------------------------------------------
# Output directory and machine-readable driver result
# ---------------------------------------------------------------------------
OUT_DIR     = project_root / "out" / "driver"
DRIVER_JSON = OUT_DIR / "kessler_driver.json"


def _field_summary(name: str, arr) -> dict:
    """Best-effort per-field summary (shape / finiteness / range) for the JSON report.

    Convenience diagnostics only — the PBS log remains the authoritative
    pass/fail signal for the driver stage (see TRANSLATE_WORKFLOW.md).
    """
    fpath = OUT_DIR / f"{name}.txt"
    info = {"written": fpath.exists()}
    try:
        a = np.asarray(arr)
        info["shape"] = list(a.shape)
        info["finite"] = bool(np.all(np.isfinite(a)))
        info["min"] = float(np.min(a))
        info["max"] = float(np.max(a))
    except Exception:
        # Never let diagnostics crash the report writer.
        info["shape"] = None
        info["finite"] = None
    return info


def _write_driver_json(result: dict) -> None:
    """Write the driver result JSON, even on failure. Convenience artifact."""
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    result["timestamp"] = datetime.now().isoformat()
    DRIVER_JSON.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")


def load_meta() -> dict:
    """Read grid parameters from meta.txt written by generate_fortran_inputs.py."""
    meta = {}
    with open(INP_DIR / "meta.txt") as f:
        for line in f:
            k, v = line.strip().split("=")
            meta[k] = float(v) if "." in v else int(v)
    return meta


def load_atmospheric_inputs(ncol: int, nz: int) -> dict:
    """
    Load atmospheric arrays from data/exp2_jd/fortran_io/inputs/.

    Files are saved as (ncol, nz) by generate_fortran_inputs.py.
    """
    def r2d(name):
        return np.loadtxt(INP_DIR / f"{name}.txt").reshape(ncol, nz)
    
    def r1d(name):
        return np.loadtxt(INP_DIR / f"{name}.txt").flatten()

    return {
        'ncol'    : ncol,
        'nz'      : nz,
        'cpair'   : r2d("cpair"),
        'rair'    : r2d("rair"),
        'rho'     : r2d("rho"),
        'z'       : r2d("z"),
        'pk'      : r2d("pk"),
        'theta'   : r2d("theta"),
        'qv'      : r2d("qv"),
        'qc'      : r2d("qc"),
        'qr'      : r2d("qr"),
        'precl'   : r1d("precl"),
        'relhum': np.zeros((ncol, nz)),   # output — initialised to zero
    }


class DriverError(Exception):
    """Raised on an expected driver failure (missing inputs or errflg != 0).

    Distinguished from unexpected exceptions so the latter can re-raise and
    surface a full traceback in the PBS log, which remains the authoritative
    pass/fail signal for the driver stage.
    """


def main():
    """
    Main driver: Initialize and run Kessler microphysics.

    Replaces:
        CALL kessler_init(...)
        CALL kessler_run(...)
    With:
        kessler_init_bridge(...)
        kessler_run_bridge(...)

    Always writes a machine-readable result to out/driver/kessler_driver.json
    (PASS or FAIL). The JSON is a convenience artifact; the PBS log remains the
    authoritative pass/fail signal (see TRANSLATE_WORKFLOW.md).
    """

    # Accumulated, always-written result. status flips to PASS only at the end.
    result = {
        "stage": "driver",
        "mode": DRIVER_MODE,
        "status": "FAIL",
        "grid": None,
        "init": {"ok": False, "errflg": None, "errmsg": None},
        "run": {"ok": False, "errflg": None, "errmsg": None, "scheme_name": None},
        "outputs": {},
        "diagnostics": {},
        "exception": None,
    }
    exit_code = 0

    print("=" * 70)
    print("Kessler Microphysics Driver - JAX Bridge Implementation")
    print(f"  bridge contract: "
          f"{'2 (device-resident)' if DRIVER_MODE == 'device_resident' else '1 (host-facing)'}"
          f"  [LAFT_DRIVER_MODE={DRIVER_MODE}]")
    print("=" * 70)

    try:
        # ==================================================================
        # Step 0: Load shared inputs
        # ==================================================================

        print(f"\n[0] Loading inputs from {INP_DIR} ...")

        if not (INP_DIR / "meta.txt").exists():
            print(f"ERROR: input files not found in {INP_DIR}")
            print("  Run first:  python data/exp2_jd/src/generate_fortran_inputs_jd.py")
            raise DriverError(f"input files not found in {INP_DIR}")

        meta = load_meta()
        ncol     = meta["ncol"]
        nz       = meta["nz"]
        dt       = meta["dt"]
        lyr_surf = int(meta["lyr_surf"])
        lyr_toa  = int(meta["lyr_toa"])

        result["grid"] = {
            "ncol": int(ncol), "nz": int(nz), "dt": float(dt),
            "seed": int(meta["seed"]), "lyr_surf": lyr_surf, "lyr_toa": lyr_toa,
        }

        atm = load_atmospheric_inputs(ncol, nz)

        print(f"✅ Inputs loaded")
        print(f"   Grid  : {ncol} columns × {nz} levels,  dt={dt} s")
        print(f"   Seed  : {int(meta['seed'])}  (set by generate_fortran_inputs.py)")

        # ==================================================================
        # Step 1: Initialize Kessler scheme
        # ==================================================================

        print("\n[1] Initializing Kessler scheme...")

        lv    = 2.5e6    # Latent heat of vaporization (J/kg)
        pref  = 1.0e5    # Reference pressure (Pa) = 1000 hPa
        rhoqr = 1000.0   # Density of liquid water (kg/m^3)
        lv_in    = lv   # Latent heat of vaporization (J/kg)
        pref_in  = pref    # Reference pressure (Pa) = 1000 hPa
        rhoqr_in = rhoqr   # Density of liquid water (kg/m^3)

        errmsg = ""
        errflg = 0

        errmsg, errflg, lv, pref, rhoqr = kessler_init_bridge(
            lv_in, pref_in, rhoqr_in, errmsg, errflg, lv, pref, rhoqr
        )

        result["init"]["errflg"] = int(errflg)
        result["init"]["errmsg"] = str(errmsg)
        if errflg != 0:
            print(f"ERROR in kessler_init: {errmsg}")
            raise DriverError(f"kessler_init errflg={errflg}: {errmsg}")
        result["init"]["ok"] = True

        print("✅ Kessler initialization successful")
        print(f"   Latent heat:        {lv:.2e} J/kg")
        print(f"   Reference pressure: {pref:.1f} hPa")
        print(f"   Water density:      {rhoqr:.1f} kg/m^3")

        # ==================================================================
        # Step 2: Run Kessler microphysics
        # ==================================================================

        print(f"\n[2] Running Kessler microphysics (dt={dt:.1f}s)...")

        # Save copies BEFORE bridge call for delta diagnostics
        theta_init = atm['theta'].copy()
        qv_init    = atm['qv'].copy()

        scheme_name = ""
        errmsg      = ""
        errflg      = 0

        if DRIVER_MODE == "host":
            # --------------------------------------------------------------
            # Contract 1 (host-facing) — unchanged legacy path: NumPy in,
            # NumPy out; the bridge does the H2D and the batched D2H itself.
            # --------------------------------------------------------------
            (theta_out, qv_out, qc_out, qr_out, precl_out, relhum_out,
             scheme_name, errmsg, errflg,
             lv, pref, rhoqr) = kessler_run_bridge(
                ncol        = atm['ncol'],
                nz          = atm['nz'],
                dt          = dt,
                lyr_surf    = lyr_surf,
                lyr_toa     = lyr_toa,
                cpair       = atm['cpair'],
                rair        = atm['rair'],
                rho         = atm['rho'],
                z           = atm['z'],
                pk          = atm['pk'],
                theta       = atm['theta'],
                qv          = atm['qv'],
                qc          = atm['qc'],
                qr          = atm['qr'],
                precl       = atm['precl'],
                relhum      = atm['relhum'],
                scheme_name = scheme_name,
                errmsg      = errmsg,
                errflg      = errflg,
                lv          = lv,
                pref        = pref,
                rhoqr       = rhoqr,
            )
        else:
            # --------------------------------------------------------------
            # Contract 2 (device-resident) — the arrays are uploaded here and
            # handed to the device entry already on the GPU; ONE batched
            # jax.device_get fetches the outputs (including errflg, checked
            # after the fetch). CHARACTER args are not in contract 2's
            # signature: strings never enter the jitted region, and contract 1
            # only ever echoes them back unchanged, so scheme_name/errmsg are
            # carried host-side here — identical observable behaviour.
            # --------------------------------------------------------------
            dev = {name: to_device(atm[name]) for name in
                   ('cpair', 'rair', 'rho', 'z', 'pk',
                    'theta', 'qv', 'qc', 'qr', 'precl', 'relhum')}

            (theta_d, qv_d, qc_d, qr_d, precl_d, relhum_d, errflg_d,
             lv, pref, rhoqr) = kessler_run_bridge_device(
                ncol        = atm['ncol'],
                nz          = atm['nz'],
                dt          = dt,
                lyr_surf    = lyr_surf,
                lyr_toa     = lyr_toa,
                cpair       = dev['cpair'],
                rair        = dev['rair'],
                rho         = dev['rho'],
                z           = dev['z'],
                pk          = dev['pk'],
                theta       = dev['theta'],
                qv          = dev['qv'],
                qc          = dev['qc'],
                qr          = dev['qr'],
                precl       = dev['precl'],
                relhum      = dev['relhum'],
                errflg      = errflg,
                lv          = lv,
                pref        = pref,
                rhoqr       = rhoqr,
            )

            (theta_out, qv_out, qc_out, qr_out, precl_out, relhum_out,
             errflg) = jax.device_get(
                (theta_d, qv_d, qc_d, qr_d, precl_d, relhum_d, errflg_d))
            theta_out  = np.asarray(theta_out,  dtype=np.float64)
            qv_out     = np.asarray(qv_out,     dtype=np.float64)
            qc_out     = np.asarray(qc_out,     dtype=np.float64)
            qr_out     = np.asarray(qr_out,     dtype=np.float64)
            precl_out  = np.asarray(precl_out,  dtype=np.float64)
            relhum_out = np.asarray(relhum_out, dtype=np.float64)
            errflg     = np.asarray(errflg).item()

        result["run"]["errflg"] = int(errflg)
        result["run"]["errmsg"] = str(errmsg)
        result["run"]["scheme_name"] = str(scheme_name)
        if errflg != 0:
            print(f"ERROR in kessler_run: {errmsg}")
            raise DriverError(f"kessler_run errflg={errflg}: {errmsg}")
        result["run"]["ok"] = True

        print(f"✅ Kessler computation successful")
        print(f"   Scheme: {scheme_name}")

        # ==================================================================
        # Step 3: Analyse and display results
        # ==================================================================

        print("\n[3] Results:")
        print("-" * 70)

        theta_change = theta_out - theta_init
        print(f"Temperature change:")
        print(f"  Mean:        {np.mean(theta_change):.4f} K")
        print(f"  Max cooling: {np.min(theta_change):.4f} K")
        print(f"  Max warming: {np.max(theta_change):.4f} K")

        qv_change = qv_out - qv_init
        print(f"\nWater vapor change:")
        print(f"  Mean:           {np.mean(qv_change)*1000:.4f} g/kg")
        print(f"  Max drying:     {np.min(qv_change)*1000:.4f} g/kg")
        print(f"  Max moistening: {np.max(qv_change)*1000:.4f} g/kg")

        print(f"\nCloud water:")
        print(f"  Mean: {np.mean(qc_out)*1000:.4f} g/kg")
        print(f"  Max:  {np.max(qc_out)*1000:.4f} g/kg")

        print(f"\nRain water:")
        print(f"  Mean: {np.mean(qr_out)*1000:.4f} g/kg")
        print(f"  Max:  {np.max(qr_out)*1000:.4f} g/kg")

        print(f"\nPrecipitation:")
        print(f"  Mean rate:           {np.mean(precl_out)*3600:.4f} mm/hr")
        print(f"  Max rate:            {np.max(precl_out)*3600:.4f} mm/hr")
        print(f"  Columns with precip: {np.sum(precl_out > 0)}/{ncol}")

        print(f"\nRelative humidity:")
        print(f"  Mean: {np.mean(relhum_out):.1f} %")
        print(f"  Min:  {np.min(relhum_out):.1f} %")
        print(f"  Max:  {np.max(relhum_out):.1f} %")

        # ==================================================================
        # Step 4: Save results
        # ==================================================================

        print("\n[4] Saving results...")

        output_dir = OUT_DIR
        output_dir.mkdir(parents=True, exist_ok=True)

        np.savetxt(output_dir / "theta.txt",  np.asarray(theta_out))
        np.savetxt(output_dir / "qv.txt",     np.asarray(qv_out))
        np.savetxt(output_dir / "qc.txt",     np.asarray(qc_out))
        np.savetxt(output_dir / "qr.txt",     np.asarray(qr_out))
        np.savetxt(output_dir / "precl.txt",  np.asarray(precl_out))
        np.savetxt(output_dir / "relhum.txt", np.asarray(relhum_out))

        with open(output_dir / "diagnostics.txt", 'w') as f:
            f.write("Kessler Microphysics Results\n")
            f.write("=" * 50 + "\n\n")
            f.write("Configuration:\n")
            f.write(f"  Columns:   {ncol}\n")
            f.write(f"  Levels:    {nz}\n")
            f.write(f"  Timestep:  {dt} s\n")
            f.write(f"  Scheme:    {scheme_name}\n\n")
            f.write("Results:\n")
            f.write(f"  Mean precipitation: {np.mean(precl_out)*3600:.4f} mm/hr\n")
            f.write(f"  Max  precipitation: {np.max(precl_out)*3600:.4f} mm/hr\n")
            f.write(f"  Mean RH:            {np.mean(relhum_out):.1f} %\n")
            f.write(f"  Temperature change: {np.mean(theta_change):.4f} K\n")

        # Per-field summary (shape / finiteness / range) for the JSON report.
        for nm, arr in [("theta", theta_out), ("qv", qv_out), ("qc", qc_out),
                        ("qr", qr_out), ("precl", precl_out), ("relhum", relhum_out)]:
            result["outputs"][nm] = _field_summary(nm, arr)

        result["diagnostics"] = {
            "mean_theta_change_K": float(np.mean(theta_change)),
            "max_cooling_K": float(np.min(theta_change)),
            "max_warming_K": float(np.max(theta_change)),
            "mean_qv_change_g_kg": float(np.mean(qv_change) * 1000),
            "mean_precip_mm_hr": float(np.mean(precl_out) * 3600),
            "max_precip_mm_hr": float(np.max(precl_out) * 3600),
            "columns_with_precip": int(np.sum(precl_out > 0)),
            "mean_relhum_pct": float(np.mean(relhum_out)),
        }

        print(f"✅ Results saved to {output_dir}/")

        # ==================================================================
        # Step 5: Visualisation (optional)
        # ==================================================================

        try:
            import matplotlib.pyplot as plt

            print("\n[5] Creating visualizations...")

            fig, axes = plt.subplots(2, 2, figsize=(12, 10))

            ax = axes[0, 0]
            ax.plot(precl_out * 3600, 'b-', linewidth=1)
            ax.set_xlabel('Column')
            ax.set_ylabel('Precipitation (mm/hr)')
            ax.set_title('Surface Precipitation Rate')
            ax.grid(True, alpha=0.3)

            ax = axes[0, 1]
            ax.plot(theta_out[0, :],  atm['z'][0, :] / 1000, 'r-',  label='Final')
            ax.plot(theta_init[0, :], atm['z'][0, :] / 1000, 'r--', alpha=0.5, label='Initial')
            ax.set_xlabel('Potential Temperature (K)')
            ax.set_ylabel('Height (km)')
            ax.set_title('Temperature Profile (Column 1)')
            ax.legend()
            ax.grid(True, alpha=0.3)

            ax = axes[1, 0]
            im = ax.contourf(relhum_out.T, levels=20, cmap='Blues')
            ax.set_xlabel('Column')
            ax.set_ylabel('Level')
            ax.set_title('Relative Humidity (%)')
            plt.colorbar(im, ax=ax)

            ax = axes[1, 1]
            total_water = (qc_out + qr_out) * 1000
            im = ax.contourf(total_water.T, levels=20, cmap='Greens')
            ax.set_xlabel('Column')
            ax.set_ylabel('Level')
            ax.set_title('Total Condensate (g/kg)')
            plt.colorbar(im, ax=ax)

            plt.tight_layout()
            plt.savefig(output_dir / 'kessler_results.png', dpi=150)
            print(f"✅ Plots saved to {output_dir}/kessler_results.png")

        except ImportError:
            print("\n[5] Matplotlib not available, skipping visualizations")

        result["status"] = "PASS"

        print("\n" + "=" * 70)
        print("✅ Kessler microphysics driver completed successfully!")
        print("=" * 70)

    except DriverError as e:
        # Expected failure: record and exit non-zero (PBS log still shows the ERROR line).
        result["exception"] = str(e)
        exit_code = 1
    except Exception:
        # Unexpected failure: record the traceback in the JSON, then re-raise so
        # the full traceback lands in the PBS log (the authoritative signal).
        result["exception"] = traceback.format_exc()
        raise
    finally:
        _write_driver_json(result)
        print(f"\n📄 Driver result written to: {DRIVER_JSON}")

    if exit_code:
        sys.exit(exit_code)


if __name__ == "__main__":
    main()